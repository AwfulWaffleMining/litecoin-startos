#!/bin/sh
# Writes litecoin.conf from the environment set in startos/main.ts, then runs
# litecoind in the foreground under StartOS supervision.
#
# The conf contains NO PASSWORD. Local callers (the sync health check,
# litecoin-cli inside this container) authenticate with the .cookie file
# litecoind writes itself; external consumers each get an `rpcauth` entry,
# which is a salted HMAC and not reversible.
set -eu

DATADIR="${LITECOIN_DATADIR:-/data/litecoin}"
CONF="$DATADIR/litecoin.conf"

# ── validate before touching the filesystem ───────────────────────────────
# Every check that can fail the start belongs here, ahead of any write, so a
# rejected configuration leaves no half-written litecoin.conf behind.

# prune and txindex are mutually exclusive, and litecoind's own error for the
# combination only arrives after it has begun loading the block index.
if [ "${PRUNE_MIB:-0}" != "0" ] && [ "${TXINDEX:-0}" = "1" ]; then
  echo "FATAL: prune and txindex cannot both be enabled." >&2
  echo "       Turn one of them off in this service's StartOS config." >&2
  exit 1
fi

mkdir -p "$DATADIR"

# Only meaningful when the datadir already existed with a hostile mode, and
# only when litecoind runs as a non-root uid — root ignores the mode bits.
if [ ! -w "$DATADIR" ]; then
  echo "FATAL: $DATADIR is not writable by uid $(id -u)" >&2
  exit 1
fi

# Written fresh on every start: StartOS config is the source of truth, so a
# hand-edit of this file inside the container is not something to preserve.
# Mode 600 before any content lands in it.
umask 077
{
  echo "# Generated by litecoin-startos on every start. Edits are discarded."
  echo "# Change these through the service's StartOS config instead."
  echo
  echo "server=1"
  echo "rpcport=${RPC_PORT:-9332}"
  echo "port=${P2P_PORT:-9333}"
  echo "dbcache=${DBCACHE_MIB:-450}"
  echo "prune=${PRUNE_MIB:-0}"
  echo "txindex=${TXINDEX:-0}"
  echo "listen=${LISTEN:-1}"

  # One rpcauth line per consumer. Each is already <user>:<salt>$<hmac>, so
  # no password is written here or held in the store — local callers such as
  # the health check use the .cookie file litecoind writes instead.
  if [ -n "${RPC_AUTH:-}" ]; then
    printf '%s\n' "$RPC_AUTH" | while IFS= read -r entry; do
      [ -n "$entry" ] && echo "rpcauth=$entry"
    done
  fi

  # The container's own address is not predictable, so RPC binds to all
  # interfaces and StartOS decides what is reachable from outside. When
  # sharing is off, only loopback is allowed to actually call in.
  echo "rpcbind=0.0.0.0"
  if [ "${SHARE_RPC:-0}" = "1" ]; then
    # StartOS gives each package a private network; allowing the RFC1918
    # ranges lets a sibling package reach this RPC without opening it to the
    # internet, which the interface layer controls separately.
    echo "rpcallowip=127.0.0.1"
    echo "rpcallowip=10.0.0.0/8"
    echo "rpcallowip=172.16.0.0/12"
    echo "rpcallowip=192.168.0.0/16"
  else
    echo "rpcallowip=127.0.0.1"
  fi
} > "$CONF"
umask 022

# A stale litecoind.pid from a hard kill confuses anyone reading the datadir.
# Remove it only when no live process holds it.
PIDFILE="$DATADIR/litecoind.pid"
if [ -f "$PIDFILE" ]; then
  oldpid="$(cat "$PIDFILE" 2>/dev/null || echo '')"
  if [ -n "$oldpid" ] && ! kill -0 "$oldpid" 2>/dev/null; then
    echo "removing stale pidfile for pid $oldpid"
    rm -f "$PIDFILE"
  fi
fi

# Never -daemon: StartOS supervises this process. Forward SIGTERM so the
# chainstate flushes, and do not exit before litecoind does, or the container
# is torn down mid-flush.
stopping=0
litecoind -datadir="$DATADIR" "$@" &
node_pid=$!
trap 'stopping=1; echo "stop requested, flushing chainstate"; kill -TERM "$node_pid" 2>/dev/null' TERM INT
wait "$node_pid"
rc=$?
if [ "$stopping" = 1 ]; then
  wait "$node_pid" || true
  exit 0
fi
exit "$rc"
